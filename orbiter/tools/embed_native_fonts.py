#!/usr/bin/env python3
"""Embed the checked-in fonts into a portable renderer resource header."""
from pathlib import Path
import sys
output, directory = map(Path, sys.argv[1:])
output.parent.mkdir(parents=True, exist_ok=True)
with output.open('w') as stream:
    stream.write('// Generated by embed_native_fonts.py; do not edit.\n#pragma once\n')
    stream.write('namespace orbiter::graphics::fonts {\n')
    for family in ('Roboto', 'JetBrainsMono'):
        for style in ('Regular', 'Bold', 'Italic', 'BoldItalic'):
            data = (directory / f'{family}-{style}.ttf').read_bytes()
            stream.write(f'inline constexpr unsigned char {family}_{style}[] = {{\n')
            for start in range(0, len(data), 32):
                stream.write(','.join(str(byte) for byte in data[start:start+32]) + ',\n')
            stream.write('};\n')
    stream.write('}\n')
