#!/usr/bin/env python3
"""Extract NASSP's bitmap resources without a Windows resource compiler.

This reads NASSP's literal BITMAP declarations and numeric resource IDs, not
arbitrary RC/preprocessor programs. Unsupported declarations and missing assets
are errors. Tables stay separate because CSM and LM reuse numeric IDs.
"""

import argparse
import json
from pathlib import Path
import re
from bmp_normalize import normalize


TABLES = (
    ("csm", "src_csm/Resources.rc", "src_csm/resource.h"),
    ("lm", "src_lm/LEMResources.rc", "src_lm/lmresource.h"),
    ("mfd", "src_mfd/MFDResources.rc", "src_mfd/MFDResource.h"),
)
BITMAP = re.compile(
    r'^\s*(\w+)\s+BITMAP\s+(?:(?:DISCARDABLE|PRELOAD|LOADONCALL|FIXED|MOVEABLE)\s+)*'
    r'"([^"\r\n]+)"\s*(?://.*)?$'
)
DEFINE = re.compile(r'^\s*#define\s+(\w+)\s+(0[xX][0-9a-fA-F]+|[0-9]+)\s*(?://.*)?$')


def resolve_case(path):
    """Return on-disk spelling even on case-insensitive macOS volumes."""
    path = Path(path).absolute()
    current = Path(path.anchor)
    for part in path.parts[1:]:
        if part == "..":
            current = current.parent
            continue
        names = [child.name for child in current.iterdir()]
        if part in names:
            current /= part
            continue
        matches = [name for name in names if name.lower() == part.lower()]
        if len(matches) != 1:
            raise ValueError(f"Missing or ambiguous resource path: {path}")
        current /= matches[0]
    return current


def collect(root, asset_prefix):
    root = Path(root).resolve()
    tables = {}
    for table, rc_name, header_name in TABLES:
        defines = {}
        for line in (root / header_name).read_text(encoding="cp1252").splitlines():
            match = DEFINE.fullmatch(line)
            if match:
                token, value = match.groups()
                defines[token] = int(value, 16 if value.lower().startswith("0x") else 10)
        entries = {}
        rc = root / rc_name
        for line_number, line in enumerate(rc.read_text(encoding="cp1252").splitlines(), 1):
            if not re.match(r'^\s*\w+\s+BITMAP\b', line):
                continue
            match = BITMAP.fullmatch(line)
            if not match:
                raise ValueError(f"{rc}:{line_number}: unsupported BITMAP declaration")
            symbol, filename = match.groups()
            resource_id = int(symbol) if symbol.isdecimal() else defines.get(symbol)
            if resource_id is None:
                raise ValueError(f"{rc}:{line_number}: undefined ID {symbol}")
            if resource_id in entries:
                raise ValueError(f"{rc}:{line_number}: duplicate bitmap ID {resource_id}")
            source = resolve_case(rc.parent / filename.replace("\\\\", "/").replace("\\", "/"))
            relative = source.relative_to(root / "Bitmaps")
            with source.open("rb") as bitmap_file:
                signature = bitmap_file.read(2)
            if signature != b"BM":
                raise ValueError(f"{rc}:{line_number}: not a BMP file: {source}")
            entries[resource_id] = {
                "id": resource_id, "symbol": symbol,
                "source": source.relative_to(root).as_posix(),
                "path": f"{asset_prefix.rstrip('/')}/{relative.as_posix()}",
            }
        if not entries:
            raise ValueError(f"No bitmaps found in {rc}")
        tables[table] = [entries[key] for key in sorted(entries)]
    return tables


def header(tables):
    lines = ["// Generated by nassp_bitmap_resources.py; do not edit.",
             "#pragma once", "#include <cstdint>", "#include <cstddef>",
             "namespace nassp::resources {",
             "struct Bitmap { std::uint32_t id; const char *path; };"]
    for table, entries in tables.items():
        lines.append(f"inline constexpr Bitmap {table}[] = {{")
        for entry in entries:
            lines.append(f'    {{{entry["id"]}, {json.dumps(entry["path"])}}}, // {entry["symbol"]}')
        lines.append("};")
    lines.extend([
        "template<std::size_t N>",
        "constexpr const char *FindBitmap(const Bitmap (&table)[N], std::uint32_t id) {",
        "    std::size_t first = 0, last = N;",
        "    while (first < last) {",
        "        const auto middle = first + (last - first) / 2;",
        "        if (table[middle].id < id) first = middle + 1;",
        "        else last = middle;",
        "    }",
        "    return first < N && table[first].id == id ? table[first].path : nullptr;",
        "}", "}", "",
    ])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-root", type=Path, required=True)
    parser.add_argument("--asset-prefix", default="ProjectApollo/Resources")
    parser.add_argument("--header", type=Path, required=True)
    parser.add_argument("--manifest", type=Path, required=True)
    parser.add_argument("--output-bitmaps", type=Path)
    args = parser.parse_args()
    if args.output_bitmaps:
        bitmap_root = args.source_root / "Bitmaps"
        for source in bitmap_root.rglob("*"):
            if source.suffix.lower() != ".bmp":
                continue
            target = args.output_bitmaps / source.relative_to(bitmap_root)
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(normalize(source.read_bytes()))
    tables = collect(args.source_root, args.asset_prefix)
    args.header.parent.mkdir(parents=True, exist_ok=True)
    args.manifest.parent.mkdir(parents=True, exist_ok=True)
    args.header.write_text(header(tables), encoding="utf-8")
    args.manifest.write_text(json.dumps(tables, indent=2) + "\n", encoding="utf-8")
    print("NASSP bitmap resources: " + ", ".join(f"{key}={len(value)}" for key, value in tables.items()))


if __name__ == "__main__":
    main()
